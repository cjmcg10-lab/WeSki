// Picks, for every Swiss resort in the Forecast catalog, the MeteoSwiss local-forecast point nearest its summit and
// its base, and writes worker/meteoswiss-points.js (issue #57, docs/FORECAST_SOURCES.md "MeteoSwiss ensembles").
//
//   node tools/build_meteoswiss_points.mjs [meta_point.csv]
//
// Without a file argument the point list is downloaded from data.geo.admin.ch (User-Agent weski-build). The list is
// ISO-8859-1 text separated by semicolons; only the id, type, height and WGS84 position are read. Rerun after the
// catalog changes (tools/build_forecast_catalog.py) or when MeteoSwiss changes its point list.
import { readFileSync, writeFileSync } from 'node:fs';

const META_URL = 'https://data.geo.admin.ch/ch.meteoschweiz.ogd-local-forecasting/ogd-local-forecasting_meta_point.csv';
const MAX_KM = 10; // a point further than this from the site is not used
const MAX_DZ = 700; // nor one whose height is more than this many metres off (temperatures are corrected for the gap)
const KM_PER_100M = 1 / 1.5; // 150 m of height gap weighs like 1 km of distance
// Sites the rule above cannot place, chosen by hand: [point_id, point_type_id, why].
const OVERRIDES = {
  zermatt: { b: [41, 1, 'the catalog base is on the Italian side (Valtournenche); MeteoSwiss has no points there, so the Zermatt station (1,638 m) stands in'] },
};

export function parsePoints(text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  const head = lines[0].split(';');
  const col = (name) => head.indexOf(name);
  const [id, type, h, la, lo] = ['point_id', 'point_type_id', 'point_height_masl', 'point_coordinates_wgs84_lat', 'point_coordinates_wgs84_lon'].map(col);
  return lines.slice(1).map((l) => l.split(';')).map((c) => ({ id: +c[id], type: +c[type], h: +c[h], lat: +c[la], lon: +c[lo] }))
    .filter((p) => [p.id, p.type, p.h, p.lat, p.lon].every(Number.isFinite));
}

const km = (a, b) => {
  const r = Math.PI / 180, x = (b.lon - a.lon) * r * Math.cos(((a.lat + b.lat) / 2) * r), y = (b.lat - a.lat) * r;
  return Math.hypot(x, y) * 6371;
};

export function nearest(points, site) {
  let best = null;
  for (const p of points) {
    const d = km(site, p), dz = Math.abs(p.h - site.h);
    if (d > MAX_KM || dz > MAX_DZ) continue;
    const cost = d + (dz / 100) * KM_PER_100M;
    if (!best || cost < best.cost) best = { p, cost, d, dz: Math.round(site.h - p.h) };
  }
  return best;
}

export function buildTable(catalog, points) {
  const F = catalog.fields, at = (k) => F.indexOf(k);
  const rows = catalog.rows.filter((r) => r[at('cc')] === 'CH' && Number.isFinite(r[at('top')]) && Number.isFinite(r[at('base')]));
  const used = new Map();
  const resorts = {};
  for (const r of rows) {
    const site = (k, lat, lon, h) => {
      const o = OVERRIDES[r[at('id')]]?.[k], p = o && points.find((q) => q.id === o[0] && q.type === o[1]);
      return p ? { p, d: km({ lat, lon }, p), dz: Math.round(h - p.h) } : nearest(points, { lat, lon, h });
    };
    const s = site('s', r[at('lat')], r[at('lon')], r[at('top')]);
    const b = site('b', r[at('baseLat')], r[at('baseLon')], r[at('base')]);
    if (!s || !b) continue;
    for (const x of [s, b]) used.set(`${x.p.id}:${x.p.type}`, x.p);
    resorts[r[at('id')]] = { s: `${s.p.id}:${s.p.type}`, b: `${b.p.id}:${b.p.type}`, dz: [s.dz, b.dz], km: [Math.round(s.d * 10) / 10, Math.round(b.d * 10) / 10] };
  }
  // points in file order: by id, then type (the order of the rows inside each hour of a MeteoSwiss file)
  const keys = [...used.values()].sort((a, b) => a.id - b.id || a.type - b.type).map((p) => [p.id, p.type]);
  const index = new Map(keys.map(([id, type], i) => [`${id}:${type}`, i]));
  const out = {};
  for (const [id, x] of Object.entries(resorts).sort()) out[id] = [index.get(x.s), index.get(x.b), x.dz[0], x.dz[1]];
  return { points: keys, resorts: out, skipped: rows.length - Object.keys(out).length };
}

async function main() {
  const file = process.argv[2];
  const text = file
    ? new TextDecoder('latin1').decode(readFileSync(file))
    : new TextDecoder('latin1').decode(await (await fetch(META_URL, { headers: { 'user-agent': 'weski-build' } })).arrayBuffer());
  const catalog = JSON.parse(readFileSync(new URL('../public/forecast/catalog-index.json', import.meta.url)));
  const table = buildTable(catalog, parsePoints(text));
  const body = `// Generated by tools/build_meteoswiss_points.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n`
    + '// points: MeteoSwiss local-forecast points [point_id, point_type_id], in file order.\n'
    + '// resorts: catalog id -> [summit point index, base point index, summit height minus point height (m), same for the base].\n'
    + `export const MS_POINTS = ${JSON.stringify(table.points)};\n`
    + `export const MS_RESORTS = ${JSON.stringify(table.resorts).replace(/\],"/g, '],\n"')};\n`;
  writeFileSync(new URL('../worker/meteoswiss-points.js', import.meta.url), body);
  console.log(`${Object.keys(table.resorts).length} Swiss resorts, ${table.points.length} points, ${table.skipped} skipped (no point within ${MAX_KM} km and ${MAX_DZ} m)`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
